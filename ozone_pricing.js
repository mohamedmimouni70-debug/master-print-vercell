function filterOzoneTarifsTable(query) {
  const tbody = document.getElementById("ozone-tarifs-tbody");
  const countEl = document.getElementById("ozone-tarifs-count");
  if (!tbody) return;

  const normQuery = normalizeMoroccanText(query);
  let matches = [];

  if (!normQuery) {
    matches = OZON_POPULAR_CITIES.map(c => ({
      name: c.ar + " / " + c.fr,
      cleanCity: c.ar,
      code: "POP",
      price: c.price,
      zone: getOzoneZoneLabel(c.price)
    }));
  } else {
    // Search in popular and official
    const seen = new Set();
    OZON_POPULAR_CITIES.forEach(c => {
      if (normalizeMoroccanText(c.ar).includes(normQuery) || normalizeMoroccanText(c.fr).includes(normQuery)) {
        matches.push({
          name: c.ar + " / " + c.fr,
          cleanCity: c.ar,
          code: "POP",
          price: c.price,
          zone: getOzoneZoneLabel(c.price)
        });
        seen.add(c.ar);
      }
    });

    OZON_OFFICIAL_CITIES.forEach(c => {
      if (normalizeMoroccanText(c.n).includes(normQuery) && !seen.has(c.n)) {
        matches.push({
          name: c.n,
          cleanCity: c.n,
          code: c.c,
          price: c.p,
          zone: getOzoneZoneLabel(c.p)
        });
        seen.add(c.n);
      }
    });
  }

  if (countEl) countEl.textContent = matches.length + " ÙˆØ¬Ù‡Ø©";

  if (matches.length === 0) {
    tbody.innerHTML = `<tr><td colspan="4" class="text-center py-6 text-xs text-[#6B6B6B]">لم يتم العثور على مدينة مطابقة. حسب تسعيرة أوزون الرسمية، المدن غير المصنفة تحتسب بـ <strong>45 درهم</strong>.</td></tr>`;
    return;
  }

  tbody.innerHTML = matches.slice(0, 100).map(m => `
    <tr class="border-b border-[#EAEAE5] hover:bg-[#FAF6EA] transition">
      <td class="py-2.5 px-3 text-xs font-bold text-[#111111]">${m.name}</td>
      <td class="py-2.5 px-3 text-[11px] text-[#6B6B6B] font-mono">${m.zone}</td>
      <td class="py-2.5 px-3 text-xs font-black ${m.price === 35 ? 'text-emerald-700' : 'text-blue-700'}">${m.price} درهم</td>
      <td class="py-2.5 px-3 text-left">
        <button type="button" onclick="selectOzoneCityFromModal('${m.name}', ${m.price})" class="px-2.5 py-1 bg-white hover:bg-[#C9A227] hover:text-white border border-[#D4D4CE] rounded-lg text-[11px] font-bold text-[#111111] transition shadow-2xs">
          اختيار للطلبية
        </button>
      </td>
    </tr>
  `).join("");
}

